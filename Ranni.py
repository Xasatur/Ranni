import asyncio

async def call_openai_api(conversation):
    return await asyncio.to_thread(
        openai.ChatCompletion.create,
        model="gpt-3.5-turbo",
        messages=conversation,
        max_tokens=2048,
        temperature=0.7,
        stop=None,
    )



@bot.command()
async def ask(ctx, *, question):
    query = "mimeType='application/pdf' and trashed=false"
    results = drive_service.files().list(q=query).execute()
    items = results.get('files', [])

    pdf_files = []

    for item in items:
        pdf_files.append({'id': item['id'], 'name': item['name'], 'content': await read_pdf_content(item['id'])})

    if pdf_files:
      answer_candidates = []
      got_answer = False
      for pdf_file in pdf_files:
          if got_answer:
              break

          chunks = textwrap.wrap(pdf_file['content'], 3000)

          for chunk in chunks:
              conversation = [
                  {"role": "system", "content": bot_personality},
                  {"role": "user", "content": f"The following text is from a PDF ({pdf_file['name']}):\n{chunk}"},
                  {"role": "user", "content": question},
              ]
              print("Calling OpenAI API...")
              response = await call_openai_api(conversation)
              print("OpenAI API response:", response)

              if 'choices' in response:
                  response_json = response['choices'][0]
                  answer = response_json["message"]["content"].strip()

                  if len(answer) > 10:
                      answer_candidates.append(answer)
                      got_answer = True
                      break
                  else:
                      print("Error:", response.get("error"))
                      await ctx.send("Sorry, there was an error processing your request.")

        # Select the best answer from the candidates
          best_answer = answer_candidates[0]
          print("Sending best answer...")
          await ctx.send(f"Answer: {best_answer}")
          print(f"Question: {question}")
          print(f"Answer: {best_answer}")
      else:
          try:
              await ctx.send("Sorry, I couldn't find any PDF files.")
          except Exception as e:
              print(f"Error sending message: {e}")




